// Writes src/styles/jp-font.css: the Shippori Mincho 600 faces whose unicode
// ranges hold the Japanese the page and the 3D covers use. The full family
// stylesheet has over 120 faces and would block the first paint for text the
// page never shows. Run it again after adding Japanese text.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const TEXT = '綺麗漫画月夜の書店茜シグナル星屑リレー灰と火種菫の書庫氷の庭祭囃子紙飛行機巻';

const require = createRequire(import.meta.url);
const source = readFileSync(require.resolve('@fontsource/shippori-mincho/600.css'), 'utf8');
const codes = [...new Set(TEXT)].map(c => c.codePointAt(0));
const faces = source
  .split('@font-face')
  .slice(1)
  .filter(face => {
    const range = face.match(/unicode-range:\s*([^;]+);/)?.[1] ?? '';
    const spans = range.split(',').map(r => {
      const [a, z] = r.trim().replace('U+', '').split('-');
      return [parseInt(a, 16), parseInt(z ?? a, 16)];
    });
    return codes.some(cp => spans.some(([a, z]) => cp >= a && cp <= z));
  })
  .map(face =>
    face
      .replace(/url\(\.\/files\//g, 'url(@fontsource/shippori-mincho/files/')
      .replace(/,\s*url\([^)]*\.woff\) format\('woff'\)/g, '')
      .replace(/\n\n\/\*[^*]*\*\/\s*$/, '\n')
  );

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'styles', 'jp-font.css');
writeFileSync(
  out,
  `/* Generated by scripts/jp-subsets.mjs: Shippori Mincho 600, only the subsets the page uses. */\n` +
    faces.map(face => `@font-face${face.trimEnd()}\n`).join('\n')
);
console.log(`${faces.length} faces written to ${out}`);
