// Regenerates THIRD_PARTY_NOTICES at the repo root.
//
//   pnpm notices           rewrite the file
//   pnpm notices --check   fail if the committed file is out of date
//
// Needs `cargo-about` on PATH (cargo install cargo-about --locked --features cli).
// Rust crates come from cargo-about (about.toml + scripts/about.hbs), JS
// production dependencies of apps/desktop from `pnpm licenses`, and the UnRAR
// licence is copied verbatim from the unrar_sys crate source.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'THIRD_PARTY_NOTICES');
const check = process.argv.includes('--check');
const isWin = process.platform === 'win32';

function run(cmd, args, opts = {}) {
  try {
    return execFileSync(cmd, args, {
      cwd: root,
      encoding: 'utf8',
      maxBuffer: 256 * 1024 * 1024,
      shell: isWin && cmd === 'pnpm',
      ...opts,
    });
  } catch (err) {
    if (err.code === 'ENOENT') {
      throw new Error(
        `\`${cmd}\` not found. Install it first (cargo install cargo-about --locked --features cli).`,
        { cause: err }
      );
    }
    throw err;
  }
}

const norm = text => text.replace(/\r\n/g, '\n').trimEnd();

function rustSection() {
  const text = run('cargo', [
    'about',
    'generate',
    '--locked',
    '--fail',
    '--config',
    'about.toml',
    'scripts/about.hbs',
  ]);
  return norm(text);
}

function unrarSection() {
  const meta = JSON.parse(run('cargo', ['metadata', '--format-version', '1', '--locked']));
  const pkg = meta.packages.find(p => p.name === 'unrar_sys');
  if (!pkg) throw new Error('unrar_sys is not in the dependency tree');
  const file = join(dirname(pkg.manifest_path), 'vendor', 'unrar', 'license.txt');
  if (!existsSync(file)) throw new Error(`UnRAR licence not found at ${file}`);
  return [
    `UnRAR licence (bundled by the unrar and unrar_sys crates, version ${pkg.version})`,
    '',
    'Used to read CBR (RAR) archives. The Rust bindings are MIT OR Apache-2.0;',
    'the vendored UnRAR C++ source is under the licence below, reproduced verbatim.',
    '',
    norm(readFileSync(file, 'utf8')),
  ].join('\n');
}

function jsSection() {
  const byLicense = JSON.parse(
    run('pnpm', ['--filter', '@kireimanga/desktop', 'licenses', 'list', '--prod', '--json'])
  );
  const rows = [];
  for (const [license, pkgs] of Object.entries(byLicense)) {
    for (const p of pkgs) {
      for (const v of p.versions) {
        const dir = p.paths.find(d => d.includes(`${p.name.replace('/', '+')}@${v}`)) ?? p.paths[0];
        rows.push({ name: p.name, version: v, license, homepage: p.homepage, dir });
      }
    }
  }
  rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

  // One licence text per distinct text, listing every package that uses it.
  const texts = new Map();
  for (const r of rows) {
    let text = '';
    for (const name of [
      'LICENSE',
      'LICENSE.md',
      'LICENSE.txt',
      'license',
      'license.md',
      'LICENCE',
    ]) {
      const f = join(r.dir ?? '', name);
      if (r.dir && existsSync(f)) {
        text = norm(readFileSync(f, 'utf8'));
        break;
      }
    }
    const key = text || `(no licence file shipped; declared ${r.license})`;
    if (!texts.has(key)) texts.set(key, []);
    texts.get(key).push(r);
  }
  const blocks = [...texts.entries()]
    .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
    .map(([text, users]) => {
      const names = users
        .map(u => `- ${u.name} ${u.version} (${u.license})${u.homepage ? ` ${u.homepage}` : ''}`)
        .join('\n');
      return `${'-'.repeat(80)}\nUsed by:\n${names}\n\n${text}`;
    });
  return blocks.join('\n\n');
}

const header = `THIRD PARTY NOTICES

KireiManga bundles the third party software listed below. Each component is
under its own licence; the notices are reproduced as required by those licences.
This file is generated by \`pnpm notices\`: do not edit it by hand.
`;

const parts = [
  header,
  `${'='.repeat(80)}\nUNRAR\n${'='.repeat(80)}\n\n${unrarSection()}`,
  `${'='.repeat(80)}\nRUST DEPENDENCIES\n${'='.repeat(80)}\n\n${rustSection()}`,
  `${'='.repeat(80)}\nJAVASCRIPT DEPENDENCIES (apps/desktop, production)\n${'='.repeat(80)}\n\n${jsSection()}`,
];
const output = `${parts.join('\n\n')}\n`;

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== output) {
    console.error('THIRD_PARTY_NOTICES is out of date. Run `pnpm notices` and commit the result.');
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES is up to date.');
} else {
  writeFileSync(outFile, output);
  console.log(`Wrote ${outFile}`);
}
